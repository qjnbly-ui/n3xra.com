create or replace function public.website_member_role(target_website_id uuid)
returns text language sql stable security definer set search_path = public as $$
  select wm.role from public.website_members wm
  where wm.website_id = target_website_id and wm.user_id = auth.uid() and wm.status = 'active' limit 1;
$$;

create or replace function public.can_view_client_website(target_website_id uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select public.is_platform_admin() or exists (
    select 1 from public.website_members wm
    where wm.website_id = target_website_id and wm.user_id = auth.uid() and wm.status = 'active'
  );
$$;

create or replace function public.can_edit_client_website(target_website_id uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select public.is_platform_admin() or exists (
    select 1 from public.website_members wm
    where wm.website_id = target_website_id and wm.user_id = auth.uid() and wm.status = 'active' and wm.role in ('owner', 'editor')
  );
$$;

create or replace function public.can_manage_client_website(target_website_id uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select public.is_platform_admin() or exists (
    select 1 from public.website_members wm
    where wm.website_id = target_website_id and wm.user_id = auth.uid() and wm.status = 'active' and wm.role = 'owner'
  );
$$;

create or replace function public.website_storage_path_id(object_name text)
returns uuid language plpgsql immutable set search_path = public as $$
declare first_segment text;
begin
  first_segment := split_part(coalesce(object_name, ''), '/', 1);
  if first_segment !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' then return null; end if;
  return first_segment::uuid;
exception when invalid_text_representation then return null;
end;
$$;

create or replace function public.next_website_asset_version_number(target_asset_id uuid)
returns integer language sql stable security invoker set search_path = public as $$
  select coalesce(max(wav.version_number), 0) + 1 from public.website_asset_versions wav where wav.asset_id = target_asset_id;
$$;

