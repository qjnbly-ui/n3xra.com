create table if not exists public.client_websites (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  live_url text,
  status text not null default 'active',
  created_by_user_id uuid references auth.users (id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint client_websites_slug_check check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint client_websites_status_check check (status in ('draft', 'active', 'paused', 'archived'))
);

create table if not exists public.website_members (
  id uuid primary key default gen_random_uuid(),
  website_id uuid not null references public.client_websites (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  role text not null default 'viewer',
  status text not null default 'active',
  invited_by_user_id uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint website_members_unique unique (website_id, user_id),
  constraint website_members_role_check check (role in ('owner', 'editor', 'viewer')),
  constraint website_members_status_check check (status in ('active', 'revoked'))
);

create table if not exists public.website_assets (
  id uuid primary key default gen_random_uuid(),
  website_id uuid not null references public.client_websites (id) on delete cascade,
  asset_key text not null,
  label text not null,
  category text not null default 'image',
  replacement_type text not null default 'html_src',
  source_file text,
  target_selector text,
  alt_text text,
  expected_aspect_ratio text,
  focal_point_x numeric(5, 2) not null default 50,
  focal_point_y numeric(5, 2) not null default 50,
  current_version_id uuid,
  status text not null default 'active',
  created_by_user_id uuid references auth.users (id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint website_assets_unique_key unique (website_id, asset_key),
  constraint website_assets_key_check check (asset_key ~ '^[a-z][a-zA-Z0-9._-]*$'),
  constraint website_assets_category_check check (category in ('image', 'logo', 'document', 'brand', 'social', 'other')),
  constraint website_assets_replacement_type_check check (replacement_type in ('html_src', 'css_background', 'carousel_slide', 'metadata', 'download_only')),
  constraint website_assets_focal_x_check check (focal_point_x between 0 and 100),
  constraint website_assets_focal_y_check check (focal_point_y between 0 and 100),
  constraint website_assets_status_check check (status in ('active', 'archived'))
);

create table if not exists public.website_asset_versions (
  id uuid primary key default gen_random_uuid(),
  asset_id uuid not null references public.website_assets (id) on delete cascade,
  version_number integer not null,
  status text not null default 'draft',
  storage_bucket text not null default 'website-assets-private',
  storage_path text not null,
  public_url text,
  original_filename text not null,
  mime_type text,
  size_bytes bigint,
  width integer,
  height integer,
  change_note text,
  uploaded_by_user_id uuid references auth.users (id) on delete set null default auth.uid(),
  approved_by_user_id uuid references auth.users (id) on delete set null,
  published_by_user_id uuid references auth.users (id) on delete set null,
  approved_at timestamptz,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint website_asset_versions_unique_version unique (asset_id, version_number),
  constraint website_asset_versions_unique_storage unique (storage_bucket, storage_path),
  constraint website_asset_versions_number_check check (version_number > 0),
  constraint website_asset_versions_status_check check (status in ('draft', 'pending_review', 'approved', 'published', 'rejected', 'archived')),
  constraint website_asset_versions_bucket_check check (storage_bucket in ('website-assets-private', 'website-assets-public')),
  constraint website_asset_versions_size_check check (size_bytes is null or size_bytes >= 0),
  constraint website_asset_versions_width_check check (width is null or width > 0),
  constraint website_asset_versions_height_check check (height is null or height > 0)
);

